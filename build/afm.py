def _tables(bold, italic):
    if bold:
        return W_BOLD
    if italic:
        return W_ITALIC
    return W_REGULAR


def text_width_units(text, bold=False, italic=False):
    """Width of ``text`` in units of 1/1000 em."""
    tbl = _tables(bold, italic)
    total = 0
    for ch in text:
        width = tbl.get(ch)
        if width is None:
            # Anything unlisted: fall back to a conservative average width.
            width = 600
        total += width
    return total


def text_width_pt(text, size_pt=12.0, bold=False, italic=False):
    return text_width_units(text, bold, italic) * size_pt / 1000.0


def text_width_tw(text, size_pt=12.0, bold=False, italic=False):
    """Width in twentieths of a point (the unit Word uses internally)."""
    return text_width_pt(text, size_pt, bold, italic) * 20.0
